/**
 * EchoCRM Extension Configuration Synchronization Script
 *
 * Reads public Supabase credentials (VITE_SUPABASE_URL, VITE_SUPABASE_ANON_KEY)
 * from the local root .env file and writes them to echocrm-extension/config.local.js.
 *
 * This allows seamless local development of the Chrome extension without
 * hardcoding credentials into committed version-controlled files.
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');

const envPath = path.join(rootDir, '.env');
const targetConfigPath = path.join(rootDir, 'echocrm-extension', 'config.local.js');

function parseEnv(filePath) {
  if (!fs.existsSync(filePath)) {
    return {};
  }
  const content = fs.readFileSync(filePath, 'utf8');
  const env = {};
  for (const line of content.split('\n')) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eqIdx = trimmed.indexOf('=');
    if (eqIdx !== -1) {
      const key = trimmed.slice(0, eqIdx).trim();
      let val = trimmed.slice(eqIdx + 1).trim();
      // Remove enclosing quotes if present
      if ((val.startsWith('"') && val.endsWith('"')) || (val.startsWith("'") && val.endsWith("'"))) {
        val = val.slice(1, -1);
      }
      env[key] = val;
    }
  }
  return env;
}

try {
  const env = parseEnv(envPath);
  const supabaseUrl = env.VITE_SUPABASE_URL || '';
  const supabaseAnonKey = env.VITE_SUPABASE_ANON_KEY || '';

  const configContent = `/**
 * EchoCRM Extension Local Configuration
 * AUTO-GENERATED by scripts/sync-extension-config.mjs - DO NOT COMMIT TO GIT
 * Generated At: ${new Date().toISOString()}
 */

globalThis.__ECHOCRM_CONFIG__ = {
  url: ${JSON.stringify(supabaseUrl)},
  anonKey: ${JSON.stringify(supabaseAnonKey)},
  bucket: 'meeting-recordings'
};
`;

  fs.writeFileSync(targetConfigPath, configContent, 'utf8');

  if (supabaseUrl && supabaseAnonKey && !supabaseUrl.includes('your-project')) {
    console.log('[EchoCRM]: ✓ Extension local configuration synchronized from .env (gitignored).');
  } else {
    console.log('[EchoCRM]: ! .env file missing or contains placeholder values. Wrote blank config.local.js.');
  }
} catch (err) {
  console.error('[EchoCRM]: Failed to sync extension config:', err.message);
  process.exit(1);
}
